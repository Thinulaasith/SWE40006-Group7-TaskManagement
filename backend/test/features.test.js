import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { getConfig } from '../src/config.js';
import { startApi } from './helpers.js';
import { validateFile } from '../src/files.js';

const password='features-test-password-2026';
test('files, roles, planning and analytics with PostgreSQL',async t=>{
  const connectionString=getConfig().databaseUrl,schemaName='taskflow_test_'+randomUUID().replaceAll('-','');
  const operator=new pg.Pool({connectionString});let db;
  t.after(async()=>{if(db)await db.end();assert.match(schemaName,/^taskflow_test_[a-f0-9]{32}$/);await operator.query(`DROP SCHEMA IF EXISTS ${schemaName} CASCADE`);await operator.end();});
  await operator.query(`CREATE SCHEMA ${schemaName}`);db=new pg.Pool({connectionString,options:`-c search_path=${schemaName}`});
  const schema=await readFile(new URL('../sql/schema.sql',import.meta.url),'utf8');await db.query(schema);await db.query(schema);
  const owner=await startApi(t,db),member=owner.newClient(),viewer=owner.newClient(),outsider=owner.newClient();
  const register=async(client,name)=> (await client('/api/auth/register',{method:'POST',body:{name,email:name.toLowerCase()+'@example.test',password,role:'admin'},status:201})).user;
  const ownerUser=await register(owner,'Owner'),memberUser=await register(member,'Member'),viewerUser=await register(viewer,'Viewer'),outsideUser=await register(outsider,'Outside');
  assert.equal(ownerUser.role,'user');
  const project=await owner('/api/projects',{method:'POST',body:{name:'Planning project'},status:201});
  for(const [email,role] of [['member@example.test','member'],['viewer@example.test','viewer']])await owner(`/api/projects/${project.id}/members`,{method:'POST',body:{email,role},status:201});
  const make=async(title,extra={})=>owner('/api/tasks',{method:'POST',body:{title,project_id:project.id,...extra},status:201});
  const first=await make('Design',{start_date:'2026-10-20',due_date:'2026-10-22'}),second=await make('Build',{start_date:'2026-10-23',due_date:'2026-10-27'});
  const upload=(client,id,name='plan.txt',raw=Buffer.from('Project plan'),status=201,headers={})=>client(`/api/tasks/${id}/attachments?name=${encodeURIComponent(name)}`,{method:'POST',raw,headers:{'Content-Type':'application/octet-stream',...headers},status});
  let file;
  await t.test('attachment storage, exact download, validation and access isolation',async()=>{
    file=await upload(member,first.id,'plan café.txt');
    assert.equal((await owner('/api/files'))[0].name,'plan café.txt');
    assert.deepEqual(await viewer(`/api/files/${file.id}/download`,{binary:true}),Buffer.from('Project plan'));
    assert.match(viewer.lastResponse.headers.get('content-disposition'),/^attachment;/);
    assert.equal(viewer.lastResponse.headers.get('x-content-type-options'),'nosniff');
    assert.equal((await outsider('/api/files')).length,0);
    await outsider(`/api/files/${file.id}/download`,{status:404});
    await upload(outsider,first.id,'plan.txt',Buffer.from('x'),404);
    await upload(viewer,first.id,'plan.txt',Buffer.from('x'),403);
    await viewer(`/api/files/${file.id}`,{method:'DELETE',status:403});
    await upload(owner,first.id,'../bad.txt',Buffer.from('x'),400);
    await upload(owner,first.id,'bad.png',Buffer.from('not a png'),400);
    await upload(owner,first.id,'script.html',Buffer.from('<script/>'),400);
    await upload(owner,first.id,'empty.txt',Buffer.alloc(0),400);
    await upload(owner,first.id,'csrf.txt',Buffer.from('x'),403,{'X-CSRF-Token':'wrong'});
    await upload(owner,first.id,'big.txt',Buffer.alloc(10485761,65),413);
    assert.throws(()=>validateFile('bad.txt',Buffer.from([0xff,0xfe])));
    assert.equal(validateFile('picture.png',Buffer.from('89504e470d0a1a0a','hex')).mime,'image/png');
    const rows=(await db.query('SELECT data FROM attachments WHERE id=$1',[file.id])).rows;assert.deepEqual(rows[0].data,Buffer.from('Project plan'));
    assert.equal((await owner(`/api/tasks/${first.id}`)).attachment_count,1);
  });
  await t.test('viewer permissions apply to every project mutation',async()=>{
    assert.equal((await viewer(`/api/tasks/${first.id}`)).can_edit,false);
    for(const [path,method,body] of [[`/tasks/${first.id}`,'PATCH',{title:'Forbidden'}],[`/tasks/${first.id}`,'DELETE',undefined],['/tasks','POST',{title:'Forbidden',project_id:project.id}],[`/tasks/${first.id}/comments`,'POST',{body:'Forbidden'}],[`/tasks/${first.id}/subtasks`,'POST',{title:'Forbidden'}],[`/tasks/${first.id}/dependencies`,'POST',{depends_on_id:second.id}],[`/projects/${project.id}/milestones`,'POST',{title:'Forbidden',due_date:'2026-10-30'}]])await viewer('/api'+path,{method,body,status:403});
    await owner(`/api/tasks/${first.id}`,{method:'PATCH',body:{assignee_id:viewerUser.id},status:400});
    await member(`/api/projects/${project.id}/members/${viewerUser.id}`,{method:'PATCH',body:{role:'member'},status:403});
    await owner(`/api/projects/${project.id}/members/${viewerUser.id}`,{method:'PATCH',body:{role:'member'}});
    await viewer(`/api/tasks/${first.id}`,{method:'PATCH',body:{assignee_id:viewerUser.id}});
    await owner(`/api/projects/${project.id}/members/${viewerUser.id}`,{method:'PATCH',body:{role:'viewer'}});
    assert.equal((await owner(`/api/tasks/${first.id}`)).assignee_id,null);
  });
  await t.test('dependency cycles, project boundaries and completion ordering',async()=>{
    await member(`/api/tasks/${second.id}/dependencies`,{method:'POST',body:{depends_on_id:first.id},status:201});
    assert.deepEqual((await owner(`/api/tasks/${second.id}`)).dependency_ids,[first.id]);
    await owner(`/api/tasks/${first.id}/dependencies`,{method:'POST',body:{depends_on_id:second.id},status:409});
    await owner(`/api/tasks/${first.id}/dependencies`,{method:'POST',body:{depends_on_id:first.id},status:400});
    const personal=await make('Personal',{project_id:null});
    await owner(`/api/tasks/${second.id}/dependencies`,{method:'POST',body:{depends_on_id:personal.id},status:400});
    await owner(`/api/tasks/${second.id}`,{method:'PATCH',body:{status:'done'},status:409});
    await owner(`/api/tasks/${first.id}`,{method:'PATCH',body:{start_date:'2026-10-25'},status:400});
    await owner(`/api/tasks/${first.id}`,{method:'PATCH',body:{project_id:null},status:409});
    await owner(`/api/tasks/${first.id}`,{method:'PATCH',body:{status:'done'}});
    const completed=await owner(`/api/tasks/${second.id}`,{method:'PATCH',body:{status:'done'}});assert.ok(completed.completed_at);
    const edit=await owner(`/api/tasks/${second.id}`,{method:'PATCH',body:{title:'Build complete'}});assert.equal(edit.completed_at,completed.completed_at);
    await owner(`/api/tasks/${first.id}`,{method:'PATCH',body:{status:'todo'},status:409});
  });
  await t.test('milestones and date-based analytics reflect persisted task state',async()=>{
    const milestone=await member(`/api/projects/${project.id}/milestones`,{method:'POST',body:{title:'Release',due_date:'2026-10-30'},status:201});
    assert.equal((await viewer('/api/milestones'))[0].can_edit,false);assert.equal((await outsider('/api/milestones')).length,0);
    await viewer(`/api/milestones/${milestone.id}`,{method:'DELETE',status:403});
    await member(`/api/milestones/${milestone.id}`,{method:'PUT',body:{title:'Release',due_date:'2026-10-31',done:true}});
    const today=new Date().toISOString().slice(0,10);
    let report=await viewer(`/api/analytics?from=${today}&to=${today}`);assert.equal(report.stats.completed_in_range,2);assert.equal(report.series.length,1);assert.equal(report.series[0].completed,2);assert.equal(report.stats.completion_rate,100);
    assert.equal((await outsider('/api/analytics')).stats.total,0);
    await owner('/api/analytics?from=2025-01-01&to=2026-12-31',{status:400});
    await owner(`/api/tasks/${second.id}`,{method:'PATCH',body:{status:'todo'}});
    report=await viewer(`/api/analytics?from=${today}&to=${today}`);assert.equal(report.stats.completed_in_range,1);assert.equal(report.stats.completion_rate,50);
    assert.equal((await owner(`/api/tasks/${second.id}`)).completed_at,null);
    await member(`/api/milestones/${milestone.id}`,{method:'DELETE',status:204});
  });
  await t.test('attachment quotas and activity history remain scoped',async()=>{
    for(let i=0;i<19;i++)await upload(owner,first.id,`file-${i}.txt`);
    await upload(owner,first.id,'overflow.txt',Buffer.from('x'),409);
    assert.equal((await viewer('/api/files')).length,20);
    await member(`/api/files/${file.id}`,{method:'DELETE',status:204});
    await viewer(`/api/files/${file.id}/download`,{status:404});
    const history=await viewer('/api/activity?limit=100');assert.ok(history.some(e=>e.action==='file.uploaded'));assert.ok(history.some(e=>e.action==='member.role_changed'));assert.ok(history.some(e=>e.action==='dependency.added'));
    assert.deepEqual(await outsider('/api/activity'),[]);
    await owner(`/api/projects/${project.id}/members/${viewerUser.id}`,{method:'DELETE',status:204});
    assert.deepEqual(await viewer('/api/activity'),[]);assert.deepEqual(await viewer('/api/files'),[]);
  });
  await t.test('administrator bootstrapping, least privilege, session revocation and last-admin protection',async()=>{
    await owner('/api/admin/users',{status:403});await outsider('/api/admin/activity',{status:403});
    await db.query("UPDATE users SET role='admin' WHERE id=$1",[ownerUser.id]);
    assert.equal((await owner('/api/admin/users')).length,4);
    await owner(`/api/admin/users/${ownerUser.id}`,{method:'PATCH',body:{disabled:true},status:400});
    await owner(`/api/admin/users/${ownerUser.id}`,{method:'PATCH',body:{role:'user'},status:409});
    await owner(`/api/admin/users/${outsideUser.id}`,{method:'PATCH',body:{role:'admin'}});
    await outsider('/api/auth/me',{status:401});
    await outsider('/api/auth/login',{method:'POST',body:{email:'outside@example.test',password}});
    await outsider(`/api/tasks/${first.id}`,{status:404});assert.deepEqual(await outsider('/api/files'),[]);
    await owner(`/api/admin/users/${memberUser.id}`,{method:'PATCH',body:{disabled:true}});
    await member('/api/tasks',{status:401});await member('/api/auth/login',{method:'POST',body:{email:'member@example.test',password},status:401});
    assert.ok((await owner('/api/admin/activity')).every(e=>e.action==='account.updated'));
    assert.ok(!(await owner('/api/activity')).some(e=>e.action==='account.updated'));
    await owner(`/api/admin/users/${memberUser.id}`,{method:'PATCH',body:{disabled:false}});
    await member('/api/auth/login',{method:'POST',body:{email:'member@example.test',password}});
    assert.equal((await member(`/api/tasks/${first.id}`)).can_edit,true);
  });
});
